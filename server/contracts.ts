import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import type { Plan } from '../src/domain/types';

/** One plan contract's text, page by page, as built by `npm run contracts` from its published PDF. */
export interface Contract {
  slug: string;
  planIds: string[];
  url: string;
  title: string;
  insurer: string;
  planYear: number;
  /** When the source address was last checked by hand. */
  checked: string;
  /** When the text was extracted. */
  builtAt: string;
  /** Hash of the PDF, so a changed document shows up when the script is run again. */
  sha256: string;
  pages: string[];
}

const money = (n: number) => `$${n.toLocaleString('en-US')}`;
const normalize = (s: string) => s.replace(/\s+/g, ' ').replace(/\$\s+/g, '$');

/** The tier part of a plan's name ("Cascade Complete Gold", "Secure Care 5"), which its contract should mention. */
export function tierName(plan: Pick<Plan, 'name'>): string {
  const m = plan.name.match(/(Cascade\b.*|Secure Care\b.*)$/);
  return (m ? m[1] : plan.name).trim();
}

export interface VerifyOptions {
  /** A contract shared by several plans, and the product name it must mention. */
  sharedName?: string;
  /** The year isn't in the text; it comes from the address, and the costs must match. */
  yearFromAddress?: boolean;
}

/**
 * Problems that suggest this isn't the plan's 2027 contract: no 2027, no mention of the plan's tier, or costs that
 * don't match the plan's 2027 deductible and out-of-pocket maximum. Empty when it checks out. A contract shared by
 * several plans lists each one's costs, so only the year and the product name are checked.
 */
export function verifyContract(pages: string[], plan: Pick<Plan, 'name' | 'benefits'>, options: VerifyOptions = {}): string[] {
  const { sharedName, yearFromAddress } = options;
  const shared = sharedName !== undefined;
  const text = normalize(pages.join(' '));
  const problems: string[] = [];
  if (!yearFromAddress && !/\b2027\b/.test(text)) problems.push('does not mention 2027');
  if (shared) {
    if (!text.toLowerCase().includes(sharedName.toLowerCase())) problems.push(`does not mention "${sharedName}"`);
    return problems;
  }
  const tier = tierName(plan);
  if (!text.toLowerCase().includes(tier.toLowerCase())) problems.push(`does not mention "${tier}"`);
  if (!plan.benefits) {
    problems.push("the plan's 2027 costs aren't known, so the contract can't be checked against them");
    return problems;
  }
  const { deductible, oopMax } = plan.benefits;
  if (!text.includes(money(deductible.individual))) problems.push(`deductible ${money(deductible.individual)} not found`);
  if (!text.includes(money(oopMax.individual))) problems.push(`out-of-pocket maximum ${money(oopMax.individual)} not found`);
  return problems;
}

/** Built contracts shipped with the server (public documents, regenerated by `npm run contracts`). */
export const CONTRACT_DIR = path.resolve(import.meta.dirname, 'contracts');

/** Each loaded contract by plan ID. */
export function loadContracts(dir = CONTRACT_DIR): Map<string, Contract> {
  const out = new Map<string, Contract>();
  let files: string[];
  try {
    files = readdirSync(dir).filter((f) => f.endsWith('.json'));
  } catch {
    return out;
  }
  for (const f of files) {
    const contract = JSON.parse(readFileSync(path.join(dir, f), 'utf8')) as Contract;
    for (const id of contract.planIds) out.set(id, contract);
  }
  return out;
}
